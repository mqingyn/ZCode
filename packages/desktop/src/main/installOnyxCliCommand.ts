/**
 * Onyx 个人构建：安装 `onyx` 命令行包装器（菜单「帮助 → 安装 onyx 命令行工具」）。
 * 复用 app 内置的 Electron Node runtime（ELECTRON_RUN_AS_NODE）执行包内 agent bundle，
 * 不要求系统安装 Node.js。见 ONYX-CHANGES.md 对应条目。
 */
import { app, dialog } from "electron";
import { mkdir, writeFile, access, constants } from "node:fs/promises";
import { dirname, join } from "node:path";

const MACOS_BIN_DIR = "~/.local/bin";

function shellQuote(value: string): string {
  return /^[A-Za-z0-9_./-]+$/.test(value) ? value : `"${value.replaceAll('"', '\\"')}"`;
}

async function pathExists(path: string): Promise<boolean> {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

/** 用户 shell 配置文件里是否已有目标 bin 目录的 PATH 导出。 */
async function hasPathExport(rcFile: string, binDir: string): Promise<boolean> {
  try {
    const content = await import("node:fs/promises").then((fs) => fs.readFile(rcFile, "utf8"));
    return content.includes(`PATH="$HOME/${binDir.replace(/^~/, "")}:$PATH"`) || content.includes(`PATH=${binDir}:$PATH`);
  } catch {
    return false;
  }
}

export async function installOnyxCliCommand(): Promise<void> {
  if (process.platform !== "darwin") {
    void dialog.showMessageBox({
      type: "info",
      message: "仅支持 macOS",
      detail: "当前版本仅支持在 macOS 上安装 onyx 命令行工具。",
    });
    return;
  }

  const electronBinary = process.execPath;
  // 打包态 agent bundle 在 Resources/glm/zcode.cjs；开发态该资源不存在时提示先打包。
  const agentBundle = join(process.resourcesPath, "glm", "zcode.cjs");
  if (!(await pathExists(agentBundle))) {
    void dialog.showMessageBox({
      type: "info",
      message: "需要打包版运行时",
      detail: "开发态没有可用的 agent bundle 资源。请先 pnpm bundle:desktop 生成安装包，再从打包版使用此菜单。",
    });
    return;
  }
  // Provider Registry 的内置配置随包放在 Resources/config/provider/；Host 拉起 agent 时
  // 经 ZCODE_BUILTIN_PROVIDER_CONFIG_FILE 显式传路径，冷启动 wrapper 沿用同一约定，
  // 否则 CLI 只能按相对入口探测，打包布局下会报"无法定位 Built-in Provider Config"。
  const builtinProviderConfig = join(process.resourcesPath, "config", "provider", "zcode-builtin.json");
  const providerConfigExists = await pathExists(builtinProviderConfig);

  const binDir = join(app.getPath("home"), ".local", "bin");
  const wrapperPath = join(binDir, "onyx");
  const wrapper = [
    "#!/bin/sh",
    `# Generated by ${app.name}. Re-run the "Install onyx command" menu item to refresh.`,
    ...(providerConfigExists
      ? [`ZCODE_BUILTIN_PROVIDER_CONFIG_FILE=${shellQuote(builtinProviderConfig)} \\`]
      : []),
    `ELECTRON_RUN_AS_NODE=1 exec ${shellQuote(electronBinary)} \\`,
    `  ${shellQuote(agentBundle)} "$@"`,
    "",
  ].join("\n");

  try {
    await mkdir(binDir, { recursive: true });
    await writeFile(wrapperPath, wrapper, { mode: 0o755 });
  } catch (error) {
    void dialog.showMessageBox({
      type: "error",
      message: "安装失败",
      detail: `写入包装器失败：${error instanceof Error ? error.message : String(error)}`,
    });
    return;
  }

  // PATH 提示：检查 zshrc（macOS 默认 shell）
  const zshrc = join(app.getPath("home"), ".zshrc");
  const pathReady = process.env.PATH?.includes(binDir) ?? false;
  const rcHasExport = await hasPathExport(zshrc, MACOS_BIN_DIR);
  let detail = `已安装到 ${wrapperPath}\n\n用法：onyx（TUI）/ onyx --web（Web 界面）/ onyx -p "..."（单次执行）。`;
  if (!pathReady && !rcHasExport) {
    detail += `\n\n注意：~/.local/bin 不在当前 PATH。请在 ~/.zshrc 添加：\nexport PATH="$HOME/.local/bin:$PATH"`;
  }

  void dialog.showMessageBox({
    type: "info",
    message: "onyx 命令行工具已安装",
    detail,
    buttons: ["好"],
  });
}
